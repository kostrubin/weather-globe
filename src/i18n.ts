export type Dictionary = typeof ru;
export function weatherLabel(code: number | null, t: Dictionary) {
  if (code === null) return t.unknown;
  return code === 0
    ? t.clear
    : code < 3
      ? t.partly
      : code === 3
        ? t.overcast
        : code < 50
          ? t.fog
          : code < 70
            ? t.rain
            : code < 80
              ? t.snow
              : code < 95
                ? t.rain
                : t.storm;
}
